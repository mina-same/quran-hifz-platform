export function getPost(slug: string): BlogPost | undefined {
  return BLOG_POSTS.find((p) => p.slug === slug);
}

/** All visible text of a post — used for word count / reading time. */
function postText(post: BlogPost): string {
  const parts: string[] = [post.title];
  for (const b of post.body) {
    if (b.type === "ul" || b.type === "ol") parts.push(...b.items);
    else if (b.type === "tip") parts.push(b.title, b.text);
    else if (b.type === "img") parts.push(b.image.caption ?? "");
    else parts.push(b.text);
  }
  for (const f of post.faq) parts.push(f.q, f.a);
  return parts.join(" ");
}

export function wordCount(post: BlogPost): number {
  return postText(post).split(/\s+/).filter(Boolean).length;
}

/** Arabic reading pace ≈ 150 words/min. */
export function readMinutes(post: BlogPost): number {
  return Math.max(1, Math.round(wordCount(post) / 150));
}

/** h2 headings → table of contents. */
export function tableOfContents(post: BlogPost): { id: string; text: string }[] {
  return post.body.filter((b): b is Extract<BlogBlock, { type: "h2" }> => b.type === "h2").map(({ id, text }) => ({ id, text }));
}
